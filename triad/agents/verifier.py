"""Deterministic Verifier: Zero-token validation gate via AST contracts and pytest."""

from __future__ import annotations

import os
from typing import Optional
from triad.core.contracts import ASTContractValidator
from triad.core.models import TaskSlice, VerificationResult
from triad.core.sandbox import IsolatedSandbox
from triad.core.token_tracker import TokenTracker


class DeterministicVerifier:
    """
    A 0-token deterministic verification gate.
    Validates AST contract adherence and executes acceptance tests.
    Zero LLM tokens are consumed for successful checks!
    """

    def __init__(self, tracker: TokenTracker):
        self.tracker = tracker

    def verify(
        self,
        task_slice: TaskSlice,
        sandbox: IsolatedSandbox,
        timeout_seconds: int = 20,
    ) -> VerificationResult:
        """Execute deterministic verification pipeline."""
        slice_id = task_slice.slice_id

        # Phase 1: AST Contract Validation (Zero tokens)
        for target_file in task_slice.target_files:
            try:
                code_content = sandbox.read_file(target_file)
            except FileNotFoundError:
                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=1,
                    failure_trace=f"Target file `{target_file}` was not generated by worker.",
                    tokens_used=0,
                )

            is_valid, errors = ASTContractValidator.validate_code(code_content, task_slice.contract)
            if not is_valid:
                error_msg = f"AST Contract Violation in `{target_file}`:\n" + "\n".join(f"- {e}" for e in errors)
                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=2,
                    failure_trace=error_msg,
                    tokens_used=0,
                )

        # Phase 2: Write Acceptance Tests (Zero tokens)
        for test_path, test_code in task_slice.acceptance_tests.items():
            sandbox.write_file(test_path, test_code)

        # Phase 3: Execute Acceptance Tests in Sandbox (Zero tokens)
        test_files = list(task_slice.acceptance_tests.keys())
        if test_files:
            cmd = f"python3 -m pytest {' '.join(test_files)} -q --tb=short"
            retcode, stdout, stderr = sandbox.exec_command(cmd, timeout_seconds=timeout_seconds)

            if retcode != 0:
                failure_summary = (
                    f"Acceptance test failure (exit code {retcode}):\n"
                    f"STDOUT:\n{stdout}\n"
                    f"STDERR:\n{stderr}"
                )
                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=retcode,
                    stdout=stdout,
                    stderr=stderr,
                    failure_trace=failure_summary,
                    tokens_used=0,
                )

        # Success! Deterministic pass achieved with 0 tokens!
        self.tracker.record_zero_token_event(
            agent_id="deterministic_verifier",
            reason=f"slice_{slice_id}_pass",
        )

        return VerificationResult(
            slice_id=slice_id,
            passed=True,
            exit_code=0,
            stdout="All contracts and acceptance tests passed deterministically.",
            tokens_used=0,
        )
