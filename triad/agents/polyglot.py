"""Polyglot verification engine for TypeScript and JavaScript workloads.

Enables Triad Swarm to verify non-Python modules deterministically using static
syntax contracts and lightweight test runner invocation (Vitest, Jest, Node test runner).
"""

from __future__ import annotations

import shutil
from typing import List

from triad.core.contracts import ASTContractValidator
from triad.core.models import TaskSlice, VerificationResult
from triad.core.sandbox import IsolatedSandbox
from triad.core.token_tracker import TokenTracker


class PolyglotTracebackPruner:
    """Specialized traceback pruner for Node.js / Vitest / Jest outputs."""

    @staticmethod
    def prune(raw_trace: str, max_lines: int = 15) -> str:
        """Strip node_modules noise and retain only assertion failures and test names."""
        if not raw_trace:
            return "Unknown verification error."

        lines = raw_trace.strip().splitlines()
        pruned: List[str] = []

        for line in lines:
            # Skip node_modules stack frames
            if "node_modules/" in line or "internal/process" in line:
                continue
            if any(m in line for m in ["FAIL", "Error:", "Expected:", "Received:", "assert", "AssertionError", "✕"]):
                pruned.append(line)
            elif pruned and line.startswith((" ", ">")):
                pruned.append(line)

            if len(pruned) >= max_lines:
                break

        if not pruned:
            pruned = [ln for ln in lines if "node_modules/" not in ln][-min(len(lines), max_lines):]

        return "\n".join(pruned[:max_lines])


class PolyglotVerifier:
    """Verifies TypeScript and JavaScript task slices inside sandboxes."""

    def __init__(self, tracker: TokenTracker):
        self.tracker = tracker

    def verify(
        self,
        task_slice: TaskSlice,
        sandbox: IsolatedSandbox,
        timeout_seconds: int = 25,
    ) -> VerificationResult:
        """Execute deterministic verification pipeline for TypeScript/JS slices."""
        slice_id = task_slice.slice_id

        # Phase 1: Static Contract Validation (0 tokens)
        for target_file in task_slice.target_files:
            try:
                code_content = sandbox.read_file(target_file)
            except (FileNotFoundError, PermissionError):
                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=1,
                    verification_phase="ast_precheck",
                    failure_trace=f"Target file `{target_file}` was not generated by worker.",
                    pruned_traceback=f"Target file `{target_file}` was not generated by worker.",
                    tokens_used=0,
                )

            is_valid, errors = ASTContractValidator.validate_code(code_content, task_slice.contract)
            if not is_valid:
                error_msg = f"TypeScript Contract Violation in `{target_file}`:\n" + "\n".join(f"- {e}" for e in errors)
                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=2,
                    verification_phase="typescript_contract",
                    ast_errors=errors,
                    failure_trace=error_msg,
                    pruned_traceback=error_msg,
                    tokens_used=0,
                )

        # Phase 2: Write Acceptance Tests (0 tokens)
        for test_path, test_code in task_slice.acceptance_tests.items():
            try:
                sandbox.write_file(test_path, test_code)
            except PermissionError:
                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=2,
                    verification_phase="typescript_contract",
                    failure_trace=f"Acceptance test path `{test_path}` is not writable in the sandbox.",
                    pruned_traceback=f"Acceptance test path `{test_path}` is not writable in the sandbox.",
                    tokens_used=0,
                )

        # Phase 3: Execute Tests if Node/Vitest/Jest available
        test_files = list(task_slice.acceptance_tests.keys())
        if test_files:
            has_node = shutil.which("node") is not None
            has_vitest = shutil.which("vitest") is not None
            has_npm = shutil.which("npm") is not None

            if has_vitest:
                cmd = f"vitest run {' '.join(test_files)}"
            elif has_node:
                # Use node native test runner if JS/TS test files present
                cmd = f"node --test {' '.join(test_files)}"
            elif has_npm:
                cmd = "npm test --if-present"
            else:
                # In environments without Node installed, static contract verification suffices deterministically
                self.tracker.record_zero_token_event(
                    agent_id="polyglot_verifier",
                    reason=f"slice_{slice_id}_ts_static_pass",
                )
                return VerificationResult(
                    slice_id=slice_id,
                    passed=True,
                    exit_code=0,
                    verification_phase="ts_static_contract_pass",
                    stdout="TypeScript static interface contract passed deterministically (Node runtime skipped).",
                    tokens_used=0,
                )

            retcode, stdout, stderr = sandbox.exec_command(cmd, timeout_seconds=timeout_seconds)
            if retcode != 0:
                failure_summary = (
                    f"TypeScript test failure (exit code {retcode}):\n"
                    f"STDOUT:\n{stdout}\n"
                    f"STDERR:\n{stderr}"
                )
                pruned = PolyglotTracebackPruner.prune(failure_summary)
                raw_token_est = int(len(failure_summary) * 0.25)
                pruned_token_est = int(len(pruned) * 0.25)
                savings = max(0, raw_token_est - pruned_token_est)
                self.tracker.record_traceback_pruning_savings(savings)

                return VerificationResult(
                    slice_id=slice_id,
                    passed=False,
                    exit_code=retcode,
                    verification_phase="polyglot_test_execution",
                    stdout=stdout,
                    stderr=stderr,
                    failure_trace=failure_summary,
                    pruned_traceback=pruned,
                    tokens_used=0,
                )

        self.tracker.record_zero_token_event(
            agent_id="polyglot_verifier",
            reason=f"slice_{slice_id}_ts_pass",
        )
        return VerificationResult(
            slice_id=slice_id,
            passed=True,
            exit_code=0,
            verification_phase="pass",
            stdout="All TypeScript contracts and tests passed deterministically.",
            tokens_used=0,
        )
